import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { extname, join, relative } from 'node:path';

const root = new URL('..', import.meta.url).pathname.replace(/^\/(.:)/, '$1');
const appRoot = join(root, 'src', 'app');
const values = new Set();
const attributes = new Set([
  'placeholder',
  'title',
  'aria-label',
  'label',
  'description',
  'emptyTitle',
  'emptyDescription',
  'searchPlaceholder',
  'deleteLabel',
  'editLabel',
  'statusLabel',
]);

const normalize = (value) => value.replace(/\s+/g, ' ').trim();
const human = (value) => {
  const text = normalize(value)
    .replace(/&amp;/g, '&')
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'");
  if (!text || text.length > 500 || /[<>{}=]/.test(text) || /^[-\d.,:]+$/.test(text)) return;
  if (/^(https?:|\/|\.\/|\.\.\/|[a-z]+\.[a-z.]+$)/i.test(text)) return;
  values.add(text);
};

const walk = async (directory) => {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) await walk(path);
    else if (extname(path) === '.html') {
      const source = await readFile(path, 'utf8');
      for (const match of source.matchAll(/>([^<]+)</g)) human(match[1]);
      for (const match of source.matchAll(/([\w-]+)="([^"]+)"/g))
        if (attributes.has(match[1])) human(match[2]);
      for (const match of source.matchAll(/'([^'\n]+)'/g)) human(match[1]);
    } else if (extname(path) === '.ts' && !entry.name.endsWith('.spec.ts')) {
      const source = await readFile(path, 'utf8');
      for (const match of source.matchAll(
        /(?:toast\.(?:success|error)|title:|message:|confirmLabel:|description:|label:)\s*(?:\()?\s*['`]([^'`$\n]+)['`]/g,
      ))
        human(match[1]);
    }
  }
};

await walk(appRoot);
const semantic = {
  'common.save': 'Save',
  'common.cancel': 'Cancel',
  'common.create': 'Create',
  'common.edit': 'Edit',
  'common.delete': 'Delete',
  'common.actions': 'Actions',
  'common.search': 'Search',
  'common.close': 'Close',
  'common.next': 'Next',
  'common.previous': 'Previous',
  'nav.dashboard': 'Dashboard',
  'nav.patients': 'Patients',
  'nav.appointments': 'Appointments',
  'nav.opd': 'OPD & Queue',
  'nav.clinical': 'Clinical EMR',
  'nav.laboratory': 'Laboratory',
  'nav.radiology': 'Radiology',
  'nav.admissions': 'Admissions & Beds',
  'nav.nursing': 'Nursing',
  'nav.procedures': 'Procedures & OT',
  'nav.pharmacy': 'Pharmacy',
  'nav.billing': 'Billing',
  'nav.insurance': 'Insurance',
  'nav.inventory': 'Inventory & Ops',
  'nav.reports': 'Reports',
  'nav.audit': 'Audit logs',
  'nav.documents': 'Documents',
  'nav.doctors': 'Doctors',
  'nav.employees': 'Employees',
  'nav.departments': 'Departments',
  'nav.users': 'Users',
  'nav.roles': 'Roles',
  'nav.support': 'Help & Support',
  'nav.settings': 'Settings',
  'header.notifications': 'Notifications',
  'header.profile': 'My Profile',
  'header.logout': 'Logout',
  'language.label': 'Language',
};
for (const value of Object.values(semantic)) values.delete(value);
const generated = Object.fromEntries(
  [...values]
    .sort((a, b) => a.localeCompare(b, 'en'))
    .map((value) => [`ui.${createHash('sha1').update(value).digest('hex').slice(0, 12)}`, value]),
);
const catalog = { ...semantic, ...generated };
const banner = `// Generated by ${relative(root, new URL(import.meta.url).pathname.replace(/^\/(.:)/, '$1')).replaceAll('\\', '/')}. Do not edit manually.\n`;
const frontendPath = join(appRoot, 'core', 'i18n', 'ui-catalog.ts');
const backendPath = join(root, 'backend', 'src', 'data', 'translation-keys.ts');
const frontendSource = `${banner}export const UI_CATALOG = ${JSON.stringify(catalog, null, 2)} as const;\n`;
const backendSource = `${banner}export const TRANSLATION_CATALOG = ${JSON.stringify(catalog, null, 2)} as const;\nexport const TRANSLATION_KEYS = Object.keys(TRANSLATION_CATALOG);\nexport const TRANSLATION_KEY_SET = new Set<string>(TRANSLATION_KEYS);\n`;
if (process.argv.includes('--check')) {
  const currentFrontend = await readFile(frontendPath, 'utf8');
  const currentBackend = await readFile(backendPath, 'utf8');
  if (currentFrontend !== frontendSource || currentBackend !== backendSource) {
    console.error('Translation catalog is stale. Run node scripts/generate-i18n-catalog.mjs.');
    process.exitCode = 1;
  } else console.log(`Translation catalog is current: ${Object.keys(catalog).length} unique keys.`);
} else {
  await writeFile(frontendPath, frontendSource);
  await writeFile(backendPath, backendSource);
  console.log(`Generated ${Object.keys(catalog).length} translation keys.`);
}
